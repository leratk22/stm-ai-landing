/**
 * Минимальный типограф для текстов кейсов.
 *
 * Ставит неразрывные пробелы там, где перенос строки выглядит сломанным:
 * перед тире, после однобуквенных предлогов и союзов, между числом
 * и единицей измерения. Тексты можно вставлять с обычными пробелами —
 * разметка всё поправит сама.
 */
const NBSP = " ";

export function tp(text: string): string {
  return (
    text
      // «слово — слово»: тире не должно уезжать в начало строки
      .replace(/ — /g, `${NBSP}— `)
      // «в городе», «и воздух»: однобуквенное слово не висит в конце строки
      .replace(/(?<=^|[\s(«])([вксуоиаВКСУОИА]) /g, `$1${NBSP}`)
      // «2 мин», «13 показателей», «390 000 ₽»
      .replace(/(\d) (?=[\dа-яёА-ЯЁ₽%])/g, `$1${NBSP}`)
  );
}
