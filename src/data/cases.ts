type CaseBase = Pick<CaseStudy, "slug" | "title" | "kind" | "year" | "preview">;

/** Всё, что не передано, берётся из шаблона-плейсхолдера. */
function fromTemplate(base: CaseBase & Partial<CaseStudy>): CaseStudy {
  return {
    meta: template.meta(base.year),
    intro: template.intro,
    sections: template.sections,
    gallery: template.gallery,
    outcome: template.outcome,
    metrics: template.metrics,
    ...base,
  };
}

