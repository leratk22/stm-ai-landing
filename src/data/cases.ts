export interface CaseMeta {
  label: string;
  value: string;
}

export interface CaseSection {
  title: string;
  paragraphs: string[];
}

export interface CaseMetric {
  value: string;
  label: string;
}

/**
 * Превью в карточке — на главной и в «Других проектах».
 * Картинка вписана в плашку 473×436 каждая по-своему, отсюда свой класс.
 */
export interface CasePreview {
  src: ImageMetadata;
  alt: string;
  class: string;
  widths: number[];
  sizes: string;
  /**
   * Посадка в слайдере героя — плашка там широкая, 414×220.
   * Все устройства прижаты к верху и обрезаны снизу, как телефон в макете.
   * width — ширина картинки в px на максимальной ширине плашки.
   */
  hero: { class: string; width: number };
}

/** Картинка на странице кейса. Если её нет — выводится заглушка. */
export interface CaseImage {
  src: ImageMetadata;
  alt: string;
  /**
   * cover (по умолчанию) — картинка той же пропорции, что плашка, заполняет окно.
   * contain — готовый мокап со своей пропорцией: встаёт целиком, без обрезки,
   * свободное место остаётся стеклом.
   */
  fit?: "cover" | "contain";
  /**
   * Масштаб для contain. У готовых мокапов свои прозрачные поля, и
   * вписанные в окно рамки они выглядят мелко — scale их подтягивает.
   * Выходящие за окно прозрачные поля обрезает плашка, корпус остаётся внутри.
   */
  scale?: number;
}

export interface CaseStudy {
  slug: string;
  /** Обложка 31:27, файл 1240×1080. Нет поля — заглушка. */
  cover?: CaseImage;
  preview: CasePreview;
  title: string;
  kind: string;
  year: string;
  meta: CaseMeta[];
  intro: string;
  sections: CaseSection[];
  /**
   * Галерея между разделами, картинки 31:22 (файл 1240×880).
   * Число — столько заглушек. В списке строка — заглушка с подписью,
   * объект — настоящая картинка.
   */
  gallery: number | (string | CaseImage)[];
  outcome: CaseSection;
  metrics: CaseMetric[];
}

